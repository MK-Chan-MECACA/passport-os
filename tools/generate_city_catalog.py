#!/usr/bin/env python3
"""Build an offline, gzip city directory. No device heap is used to serve it.

Source: GeoNames cities5000 rows for Malaysia (CC BY 4.0). Coordinates are
weather-location coordinates, not an administrative-division register.
"""
import argparse
import csv
import gzip
import hashlib
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'third_party/geonames-my'
SNAPSHOTS = {
    'cities5000_MY.txt': '2bf6959171fc91fcfa69d454d713a3548f90db5040ba1e32fa7fe8713d4cc193',
    'admin1_MY.txt': 'ca9672dc4c335cc0db72ed09231fc120f3e5a75c7666eee69790916bd81c8b08',
}


def read_snapshot(name):
    raw = (DATA / name).read_bytes()
    assert hashlib.sha256(raw).hexdigest() == SNAPSHOTS[name], f'{name} snapshot changed'
    return list(csv.reader(raw.decode('utf-8').splitlines(), delimiter='\t', quoting=csv.QUOTE_NONE))


def generate():
    states = {code.split('.')[1]: name for code, name, *_ in read_snapshot('admin1_MY.txt')}
    assert len(states) == 16, 'expected 13 states + 3 federal territories'
    places = []
    seen = set()
    for r in read_snapshot('cities5000_MY.txt'):
        if len(r) != 19 or r[8] != 'MY':
            raise ValueError(f'bad row: {r[:3]}')
        geonameid, name, lat, lon, admin1, population = r[0], r[1], r[4], r[5], r[10], int(r[14])
        state = states[admin1]
        latitude, longitude = round(float(lat), 4), round(float(lon), 4)
        if not (0 <= latitude <= 8 and 99 <= longitude <= 120):
            raise ValueError(f'coordinate out of range: {geonameid}')
        if (state, name) in seen:
            raise ValueError(f'duplicate place: {name}, {state}')
        seen.add((state, name))
        # id, display name, latitude, longitude, state, radio parent (= state), radio country
        places.append((-population, name, [geonameid, name, latitude, longitude, state, state, 'MY']))
    rows = [row for *_, row in sorted(places)]
    assert len(rows) >= 500 and {r[4] for r in rows} == set(states.values())
    assert rows[0][1] == 'Kuala Lumpur'
    payload = json.dumps(rows, ensure_ascii=False, separators=(',', ':')).encode('utf-8')
    compressed = io.BytesIO()
    with gzip.GzipFile(filename='', fileobj=compressed, mode='wb', compresslevel=9, mtime=0) as writer:
        writer.write(payload)
    symbols = ''.join(sorted(set(''.join(r[1] + r[4] for r in rows)))) + '\n'
    outputs = {
        ROOT / 'main/apps/home/cities.json': payload + b'\n',
        ROOT / 'main/apps/home/cities.json.gz': compressed.getvalue(),
        ROOT / 'main/fonts/city_symbols.txt': symbols.encode('utf-8'),
        ROOT / 'main/apps/radio/radio_cities.inc': (
            '// Generated by tools/generate_city_catalog.py from GeoNames (CC BY 4.0).\n'
            + ''.join(f'{{"{r[1]}", "{r[4]}"}},\n' for r in sorted(rows, key=lambda r: (r[1], r[4])))
        ).encode('utf-8'),
    }
    return rows, outputs


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    rows, outputs = generate()
    for path, value in outputs.items():
        if args.check:
            assert path.read_bytes() == value, f'regenerate {path.relative_to(ROOT)}'
        else:
            path.write_bytes(value)
    print(f'City catalog: {len(rows)} locations, {len({r[4] for r in rows})} states/territories, '
          f'{len(outputs[ROOT / "main/apps/home/cities.json.gz"])} bytes in flash')
